import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createLocalLeaderboard } from '../src/progression/local-leaderboard.mjs';
const values = new Map(), storage = { getItem: key => values.get(key), setItem: (key, value) => values.set(key, value) };
const now = () => Date.UTC(2026, 8, 18);
const record = { runId: 'run-1', name: 'Lucca', score: 120, kills: 12, wave: 2, level: 3, build: ['Dano +16%'], durationMs: 30000 };
const results = [];
const check = name => results.push({ name, passed: true });
let ledger = createLocalLeaderboard(storage, { now });
assert.equal(ledger.record(record).recorded, true);
assert.equal(ledger.record(record).recorded, false);
assert.equal(ledger.snapshot().players[0].gamesPlayed, 1);
check('Repeated run cannot duplicate score, kills or games');
ledger = createLocalLeaderboard(storage, { now });
assert.equal(ledger.record(record).recorded, false);
assert.equal(ledger.snapshot().players[0].totalScore, 120);
check('Reload preserves records and retry deduplication');
ledger.record({ ...record, runId: 'run-2', name: 'LUCCA', score: 80, kills: 8, level: 2 });
const twoRuns = ledger.snapshot();
assert.equal(twoRuns.totalPlayers, 1); assert.equal(twoRuns.players[0].totalScore, 200); assert.equal(twoRuns.players[0].bestScore, 120); assert.equal(twoRuns.players[0].bestLevel, 3);
check('Same normalized name accumulates once and preserves best run');
twoRuns.players[0].bestScore = 9999;
assert.equal(ledger.snapshot().players[0].bestScore, 120);
check('Returned snapshots cannot mutate stored records');
ledger.record({ ...record, runId: 'run-3', name: '__proto__', score: 130 });
assert.equal(ledger.snapshot().totalPlayers, 2); assert.equal(ledger.snapshot().players[0].name, '__proto__');
check('Names cannot mutate object prototypes');
const unavailable = createLocalLeaderboard({ getItem() { throw Error('Denied'); }, setItem() { throw Error('Quota'); } }, { now });
assert.equal(unavailable.record(record).recorded, true); assert.equal(unavailable.snapshot().players[0].bestScore, 120); assert.equal(unavailable.snapshot().persistence, false);
check('Storage refusal retains current-session record and reports no persistence');
const malformed = createLocalLeaderboard({ getItem: () => '{broken', setItem() {} }, { now });
assert.equal(malformed.snapshot().totalPlayers, 0); assert.equal(malformed.record(record).recorded, true);
check('Malformed saved JSON cannot break gameplay');
assert.equal(ledger.record({ ...record, runId: '' }).recorded, false);
ledger.record({ ...record, runId: 'bad-values', name: '<SFX>', score: -30, kills: Infinity, wave: NaN, level: null, build: ['<script>'] });
const cleaned = ledger.snapshot().players.find(player => player.name === 'SFX');
assert.equal(cleaned.lastScore, 0); assert.equal(cleaned.lastWave, 1); assert.equal(cleaned.lastLevel, 1); assert.deepEqual(cleaned.lastBuild, ['script']);
check('Missing identity rejected; malformed scalar/name/build data bounded');
const directory = process.env.BIPX_EVIDENCE_DIR || `output/playwright/${new Date().toISOString().replace(/[:.]/g, '-')}-local-records`;
fs.mkdirSync(directory, { recursive: true });
fs.writeFileSync(path.join(directory, 'local-records.json'), JSON.stringify({ scope: 'Actual personal-record reducer CPU tests; no shared server writes or native UI proof', passed: true, results }, null, 2));
console.log(JSON.stringify({ passed: true, checks: results.length, directory }));
